"""Build the plain, unbranded (LinkedIn) variant of the Surviving deck from the Innopolis source.

Drops the readers' thank-you slide and the Russian annex, removes the Innopolis affiliation and the
section colour tags, and recolours charts to a muted neutral palette. Theme: neutral.css (this folder).

Rebuild after any change to the source deck, from _misc/Surviving:
  python3 slides_linkedin/build_from_inno.py .
  cd slides_linkedin/media && for f in *.vl.json; do npx -y -p vega -p vega-lite -p vega-cli vl2svg $f ${f%.vl.json}.svg </dev/null; done
  /Applications/draw.io.app/Contents/MacOS/draw.io -x -f svg -e -b 10 --embed-svg-fonts false -o five-forces.svg five-forces.drawio
  cd .. && marp Surviving-the-Agent-Era.md --theme neutral.css --allow-local-files --html --no-stdin --pdf -o Surviving-the-Agent-Era.pdf
"""
import re, pathlib, sys
root = pathlib.Path(sys.argv[1])
src = (root/'slides/Surviving-the-Agent-Era.md').read_text()
out = root/'slides_linkedin'
COL = {'#019546':'#3b6ea8','#a5d6a7':'#b6c8de','#81c784':'#8aa9cc','#2D6E2A':'#1f3b5c',
       '#dc2626':'#b5473a','#f59e0b':'#c9a227','#e6f4ea':'#eef2f7','#f0f8f0':'#f6f8fa'}
def recolor(t):
    for a,b in COL.items(): t = re.sub(re.escape(a), b, t, flags=re.I)
    return t
body = src[src.index('\n---\n', 4)+5:]
DROP = ('# Thank You to the Readers', '# In Russian IT', '# Yandex and Sber', '# In Russia, the Economy', '# References: Russian Market Annex')
kept = []
for s in re.split(r'\n---\n', body):
    if any(d in s for d in DROP): continue
    s = re.sub(r'<!-- class: [^>]*-->\n*', '', s)
    def cls(m):
        parts = [p for p in m.group(1).split() if not re.fullmatch(r'b\d', p)]
        return f'<!-- _class: {" ".join(parts)} -->' if parts else ''
    s = re.sub(r'<!-- _class: ([^>]*?) -->', cls, s)
    # content slides without a tier get the large tier (the source deck default was xl)
    if not re.search(r'_class: [^>]*(title|lead|closing|xl|large|dense)', s) and '# References' not in s:
        if re.search(r'<!-- _class: ([^>]*?) -->', s):
            s = re.sub(r'<!-- _class: ([^>]*?) -->', lambda m: f'<!-- _class: large {m.group(1)} -->', s, count=1)
        else:
            s = '<!-- _class: large -->\n\n' + s.lstrip('\n')
    kept.append(s)
deck = '\n---\n'.join(kept)
deck = deck.replace('Andrey Sadovykh · Innopolis University', 'Andrey Sadovykh')
deck = deck.replace(" It is not only Russia's problem.", '')
deck = deck.replace('## Where the numbers come from, and the Russian market', '## Where the numbers come from')
front = '---\nmarp: true\ntheme: neutral\npaginate: true\n---\n\n'
header = '<!-- Plain variant, generated by build_from_inno.py from ../slides/Surviving-the-Agent-Era.md. Edit the source deck, then re-run. -->\n\n'
(out/'Surviving-the-Agent-Era.md').write_text(front + header + deck.lstrip('\n'))
for svg in sorted(set(re.findall(r'media/([a-z0-9-]+)\.svg', deck))):
    vl = root/'slides/media'/f'{svg}.vl.json'
    if vl.exists():
        (out/'media'/f'{svg}.vl.json').write_text(recolor(vl.read_text()))
    elif svg == 'five-forces':
        (out/'media/five-forces.drawio').write_text(recolor((root/'slides/media/five-forces.drawio').read_text()))
print(len(kept), 'slides')
