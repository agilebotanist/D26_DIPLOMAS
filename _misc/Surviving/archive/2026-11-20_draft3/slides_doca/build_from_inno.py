"""Build the Docaposte variant of the Surviving deck from the Innopolis source.
Drops the readers' thank-you slide and the Russian annex (four slides), maps section colours to Docaposte
section themes, sets content slides to the large tier, and recolours charts to the Docaposte palette.

Rebuild after any change to the source deck, from _misc/Surviving:
  python3 slides_doca/build_from_inno.py .
  cd slides_doca/media && for f in *.vl.json; do npx -y -p vega -p vega-lite -p vega-cli vl2svg $f ${f%.vl.json}.svg </dev/null; done
  /Applications/draw.io.app/Contents/MacOS/draw.io -x -f svg -e -b 10 --embed-svg-fonts false -o five-forces.svg five-forces.drawio
  cd .. && T=~/.claude/skills/synced/*/doca-marp/themes/docaposte.css
  marp Surviving-the-Agent-Era-Docaposte.md --theme $T --allow-local-files --html --no-stdin --pdf -o Surviving-the-Agent-Era-Docaposte.pdf
"""
import re, json, pathlib, subprocess, sys
root = pathlib.Path(sys.argv[1])
src = (root/'slides/Surviving-the-Agent-Era.md').read_text()
out = root/'slides_doca'
COL = {'#019546':'#0000FF','#a5d6a7':'#9999FF','#81c784':'#6666FF','#2D6E2A':'#00008B','#2d6e2a':'#00008B',
       '#dc2626':'#FF5657','#f59e0b':'#FFCB05','#e6f4ea':'#E6E6FF','#f0f8f0':'#F2F2FF'}
def recolor(t):
    for a,b in COL.items(): t = re.sub(re.escape(a), b, t, flags=re.I)
    return t
# frontmatter
body = src.split('\n---\n', 1)[1] if src.startswith('---') else src
body = body.split('\n---\n',1)[1] if body.lstrip().startswith('marp') else body
fm = src.index('\n---\n', 4)
body = src[fm+5:]
slides = re.split(r'\n---\n', body)
DROP = ('# Thank You to the Readers', '# In Russian IT', '# Yandex and Sber', '# In Russia, the Economy', '# References: Russian Market Annex')
DEFAULT_TIER = ('# Three Readings of the Cuts', '# Aim Here, Not There')
THEMES = {'b1':'theme-blue','b2':'theme-mint','b3':'theme-poussin','b4':'theme-yellow','b8':'theme-blue'}  # violet and coral put amber subtitles on low-contrast backgrounds
kept = []
for s in slides:
    if any(d in s for d in DROP): continue
    s = re.sub(r'<!-- class: [^>]*-->\n*', '', s)          # carried tier/colour classes
    def lead(m):
        b = re.search(r'b\d', m.group(1)); return f'<!-- _class: "section {THEMES.get(b.group(0) if b else "b1")}" -->'
    s = re.sub(r'<!-- _class: lead([^>]*)-->', lead, s)
    def cls(m):
        parts = [p for p in m.group(1).split() if not re.fullmatch(r'b\d|xl|large', p)]
        return f'<!-- _class: {" ".join(parts)} -->' if parts else ''
    s = re.sub(r'<!-- _class: ((?!title|closing|"section)[^>]*?) -->', cls, s)
    # content slides use the large tier (titles held at 40px in the frontmatter style); references stay default
    # dense tables collide with the two-line footer at the large tier: keep the default tier there
    if any(t in s for t in DEFAULT_TIER):
        s = s.replace('table-xlarge', 'table-large')
    elif not re.search(r'_class: (title|closing|"section)', s) and '# References' not in s:
        if re.search(r'<!-- _class: ([^>]*?) -->', s):
            s = re.sub(r'<!-- _class: ([^>]*?) -->', lambda m: f'<!-- _class: large {m.group(1)} -->', s, count=1)
        else:
            s = '<!-- _class: large -->\n\n' + s.lstrip('\n')
    kept.append(s)
deck = '\n---\n'.join(kept)
deck = deck.replace('Andrey Sadovykh · Innopolis University', 'Andrey Sadovykh')
deck = deck.replace(' It is not only Russia\'s problem.', '')
deck = deck.replace('## Where the numbers come from, and the Russian market', '## Where the numbers come from')
front = '''---
marp: true
theme: docaposte
paginate: true
style: |
  section footer { right: 330px; font-size: 11px; line-height: 1.25; }
  section.large h1 { font-size: 40px; }
---
'''
header = '<!-- Docaposte variant, generated by to_doca.py from ../slides/Surviving-the-Agent-Era.md. Edit the source deck, then re-run; do not edit this file by hand. -->\n\n'
(out/'Surviving-the-Agent-Era-Docaposte.md').write_text(front + '\n' + header + deck.lstrip('\n'))
# charts
for svg in sorted(set(re.findall(r'media/([a-z0-9-]+)\.svg', deck))):
    vl = root/'slides/media'/f'{svg}.vl.json'
    if vl.exists():
        (out/'media'/f'{svg}.vl.json').write_text(recolor(vl.read_text()))
    elif svg == 'five-forces':
        (out/'media/five-forces.drawio').write_text(recolor((root/'slides/media/five-forces.drawio').read_text()))
print(len(slides), '->', len(kept), 'slides')
